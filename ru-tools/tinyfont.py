def text_mask(txt, font, gap=1, space=3):
    """-> (list_of_rows (strings), width)"""
    h = len(next(iter(font.values())))
    cols = []
    for ch in txt:
        if ch == ' ':
            cols.append(['.'] * space * 1)  # placeholder
            cols[-1] = None
            continue
        cols.append(font[ch])
    # собрать
    rows = [''] * h
    first = True
    for gl in cols:
        if gl is None:
            for r in range(h): rows[r] += '.' * (space - (0 if first else 0))
            continue
        if not first and rows[0] != '' :
            for r in range(h): rows[r] += '.' * gap
        for r in range(h): rows[r] += gl[r]
        first = False
    return rows, len(rows[0])

