G = {}
def add(ch, rows):
    assert len(rows) in (7, 8) or len(rows) == 8, (ch, len(rows))
    rows = list(rows) + ['........'] * (8 - len(rows))
    for r in rows:
        assert len(r) == 8, (ch, r)
    G[ch] = rows

