# гомоглифы из латиницы
HOMO = {'А':'A','В':'B','Е':'E','К':'K','М':'M','Н':'H','О':'O','Р':'P','С':'C','Т':'T','Х':'X','У':'Y',
        'а':'a','е':'e','о':'o','р':'p','с':'c','х':'x','у':'y'}

def cp1251(ch):
    return ch.encode('cp1251')[0]

def main(src, dst):
    im = Image.open(src).convert('RGB')
    ink = min(im.getdata(), key=sum)           # самый тёмный цвет шрифта
    ROWS = 14
    out = Image.new('RGB', (128, ROWS * 8), (255, 255, 255))
    out.paste(im, (0, 0))
    def put(code, bits):
        i = code - 32
        x, y = (i % 16) * 8, (i // 16) * 8
        for r, line in enumerate(bits):
            for c, v in enumerate(line):
                if v == '#':
                    out.putpixel((x + c, y + r), ink)
    def latin_bits(ch):
        i = ord(ch) - 32
        x, y = (i % 16) * 8, (i // 16) * 8
        return [''.join('#' if sum(im.getpixel((x + c, y + r))) < 384 else '.' for c in range(8)) for r in range(8)]
    for cy, la in HOMO.items():
        put(cp1251(cy), latin_bits(la))
    for cy, bits in G.items():
        put(cp1251(cy), bits)
    out.save(dst)
    missing = [chr(c) for c in list(range(0x410, 0x450)) + [0x401, 0x451]
               if chr(c) not in G and chr(c) not in HOMO]
    print('missing:', missing)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
